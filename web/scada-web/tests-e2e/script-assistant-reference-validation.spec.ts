test('literal references generated by the assistant validate against the current project catalog', () => {
  const source = [
    'from elite_scada import tag_read, tag_write, visual_property_read, client_memory_read',
    'value = await tag_read("tag-live")',
    'await tag_write("tag-live", 1)',
    'visible = await visual_property_read("button-live", "visible")',
    'mode = await client_memory_read("memory-live")'
  ].join('\n');

  expect(validateScriptAssistantReferences(source, catalog)).toEqual([]);
});

test('deleted TAG, object, property and Client Memory references remain invalid and are reported without substitution', () => {
  const source = [
    'value = await tag_read("tag-deleted")',
    'visible = await visual_property_read("button-deleted", "visible")',
    'text = await visual_property_read("button-live", "text")',
    'mode = await client_memory_read("memory-deleted")'
  ].join('\n');

  expect(validateScriptAssistantReferences(source, catalog)).toEqual([
    expect.objectContaining({ code: 'SCRIPT_REFERENCE_TAG_MISSING', line: 1, reference: 'tag-deleted' }),
    expect.objectContaining({ code: 'SCRIPT_REFERENCE_OBJECT_MISSING', line: 2, reference: 'button-deleted', propertyKey: 'visible' }),
    expect.objectContaining({ code: 'SCRIPT_REFERENCE_PROPERTY_MISSING', line: 3, reference: 'button-live', propertyKey: 'text' }),
    expect.objectContaining({ code: 'SCRIPT_REFERENCE_CLIENT_MEMORY_MISSING', line: 4, reference: 'memory-deleted' })
  ]);

  expect(JSON.stringify(validateScriptAssistantReferences(source, catalog))).not.toContain('tag-live');
});

test('dynamic Python references are not guessed or rewritten by the conservative validator', () => {
  const source = [
    'tag_id = choose_tag()',
    'value = await tag_read(tag_id)',
    'object_id = current_object()',
    'await visual_property_write(object_id, "visible", True)'
  ].join('\n');

  expect(validateScriptAssistantReferences(source, catalog)).toEqual([]);
});
