const resources: Record<EngineeringLocale, Record<TranslationKey, string>> = {
  'pt-BR': ptBR,
  en,
  es
};

export function resolveInitialLocale(): EngineeringLocale {
  const saved = window.localStorage.getItem('elitescada.engineering.locale');
  if (saved === 'pt-BR' || saved === 'en' || saved === 'es') return saved;
  const browser = window.navigator.language.toLowerCase();
  if (browser.startsWith('en')) return 'en';
  if (browser.startsWith('es')) return 'es';
  return 'pt-BR';
}

export function setStoredLocale(locale: EngineeringLocale) {
  window.localStorage.setItem('elitescada.engineering.locale', locale);
}

export function translator(locale: EngineeringLocale) {
  return (key: TranslationKey) => resources[locale][key] ?? ptBR[key];
}
